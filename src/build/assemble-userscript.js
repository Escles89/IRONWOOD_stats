'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '../..');
const modules = require('./modules.json');
const outputPath = path.join(root, 'ironwood-stats.user.js');
function validate(output) {
  const metadata = output.match(/^\/\/ ==UserScript==\n[\s\S]*?^\/\/ ==\/UserScript==$/m)?.[0];
  if (!metadata) throw new Error('Missing userscript metadata block');
  for (const name of ['name', 'namespace', 'version', 'description', 'license', 'match', 'grant', 'run-at', 'noframes']) {
    if (!new RegExp(name === 'noframes' ? '^// @noframes$' : `^// @${name}\\s+\\S.*$`, 'm').test(metadata)) throw new Error(`Missing @${name}`);
  }
  if (!/^\/\/ @match\s+https:\/\/ironwoodrpg\.com\/\*$/m.test(metadata)) throw new Error('Unexpected match scope');
  if (Buffer.byteLength(output) >= 2097152) throw new Error('Greasy Fork size limit exceeded');
  new vm.Script(output, { filename: outputPath });
  return output;
}
function assemble() {
  const metadata = fs.readFileSync(path.join(__dirname, 'metadata.txt'), 'utf8').trimEnd();
  const version = metadata.match(/^\/\/ @version\s+(\S+)$/m)?.[1];
  if (!version) throw new Error('Missing @version');
  const outlets = JSON.parse(fs.readFileSync(path.join(root, 'src/content/news-outlets.json'), 'utf8'));
  const news = JSON.parse(fs.readFileSync(path.join(root, 'src/content/news-lines.json'), 'utf8'));
  if (!news.general?.length || Object.values(news).some(lines => !Array.isArray(lines) || !lines.length || lines.some(line => typeof line !== 'string' || !line.trim()))) throw new Error('Invalid news lines');
  const css = fs.readFileSync(path.join(root, 'src/apps/status/styles.css'), 'utf8');
  const notices = fs.readFileSync(path.join(root, 'LICENSE'), 'utf8').split('\n').filter(line => line.startsWith('Required Notice:')).join('\n');
  const license = `/*\nPolyForm Noncommercial License 1.0.0\nhttps://polyformproject.org/licenses/noncommercial/1.0.0\n\n${notices}\n*/`;
  const body = modules.map(file => {
    const source = fs.readFileSync(path.join(root, 'src', file), 'utf8').trimEnd();
    new vm.Script(source, { filename: file });
    return `  // Source: ${file}\n${source}`;
  }).join('\n\n');
  return validate(`${metadata}\n\n${license}\n\n// Generated by src/build/assemble-userscript.js. Edit src/, then run npm run build.\n(() => {\n  'use strict';\n  const USERSCRIPT_VERSION = ${JSON.stringify(version)};\n  const STATUS_STYLES = ${JSON.stringify(css)};\n  const NEWS_LINES = ${JSON.stringify(news)};\n  const NEWS_OUTLETS = ${JSON.stringify(outlets)};\n\n${body}\n})();\n`);
}
if (require.main === module) {
  const output = assemble();
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(outputPath, 'utf8') !== output) throw new Error('Generated userscript is stale; run npm run build');
  } else fs.writeFileSync(outputPath, output);
  console.log(`Userscript validated: ${Buffer.byteLength(output)} bytes`);
}
module.exports = { assemble, validate, modules, root };
